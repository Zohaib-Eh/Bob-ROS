import importlib
import math
import sys
import types
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import pytest

from app.ros.chain import parse_chain
from app.ros.fk import fk
from app.ros.moveit_config import generate
from tests.ros_helpers import two_joint_zip, unzip

_X = np.eye(4)
_X[0, 3] = 0.1  # fake EAIK's end frame sits 0.1 m past the URDF tip


def _fake_eaik(monkeypatch, fail=False):
    class UrdfRobot:
        def __init__(self, path):
            if fail:
                raise RuntimeError("no decomposition")
            self.chain = parse_chain(Path(path).read_text())

        def hasKnownDecomposition(self):
            return True

        def fwdKin(self, q):
            return fk(self.chain, q) @ _X

        def IK(self, P):
            R = np.asarray(P)[:3, :3]  # bot: R = Rz(q1) @ Ry(q2)
            q = np.array([math.atan2(-R[0, 1], R[1, 1]), math.atan2(-R[2, 0], R[2, 2])])
            return SimpleNamespace(Q=[q, q + [2 * math.pi, 0], q + [0, 0.3]])  # real, 2π twin, wrong

    sub = types.ModuleType("eaik.IK_URDF")
    sub.UrdfRobot = UrdfRobot
    pkg = types.ModuleType("eaik")
    pkg.IK_URDF = sub
    monkeypatch.setitem(sys.modules, "eaik", pkg)
    monkeypatch.setitem(sys.modules, "eaik.IK_URDF", sub)


@pytest.fixture
def kin(tmp_path, monkeypatch):
    d = unzip(two_joint_zip(tmp_path), tmp_path / "x")
    src = tmp_path / "ws" / "src"
    generate("bot", d / "bot", src, source="bot.zip", samples=50)
    monkeypatch.syspath_prepend(str(src / "bot_kinematics"))
    for name in [m for m in sys.modules if m.startswith("bot_kinematics")]:
        monkeypatch.delitem(sys.modules, name)
    mod = importlib.import_module("bot_kinematics")
    return mod, src / "bot" / "urdf" / "bot.urdf"


def test_solve_all_returns_each_real_solution_once(kin, monkeypatch):
    _fake_eaik(monkeypatch)
    mod, urdf = kin
    k = mod.Kinematics(str(urdf))
    q = np.array([0.3, -0.4])
    sols = k.solve_all(k.fk(q))
    assert len(sols) == 1 and sols[0] == pytest.approx(q)


def test_solutions_outside_joint_limits_are_dropped(kin, monkeypatch):
    _fake_eaik(monkeypatch)
    mod, urdf = kin
    k = mod.Kinematics(str(urdf))
    assert k.solve_all(k.fk([0.3, 1.6])) == []   # hand_joint limit is ±1.5


def test_geometry_eaik_cannot_solve_says_so(kin, monkeypatch):
    _fake_eaik(monkeypatch, fail=True)
    mod, urdf = kin
    k = mod.Kinematics(str(urdf))
    assert k.fk([0.0, 0.0])[:3, 3] == pytest.approx([0.5, 0, 0.2])   # FK still works
    with pytest.raises(NotImplementedError, match="no closed-form solver for this geometry"):
        k.solve_all(np.eye(4))


def test_package_files_carry_the_note(tmp_path):
    d = unzip(two_joint_zip(tmp_path), tmp_path / "x")
    src = tmp_path / "ws" / "src"
    generate("bot", d / "bot", src, source="bot.zip", samples=50)
    pkg = src / "bot_kinematics"
    assert (pkg / "resource" / "bot_kinematics").exists()
    for p in [p for p in pkg.rglob("*") if p.is_file() and p.parent.name != "resource"]:
        assert "Generated by cad-to-urdf from bot.zip" in p.read_text(), p.name
    assert 'ROBOT = "bot"' in (pkg / "bot_kinematics" / "solver.py").read_text()


def test_eaik_sees_the_arm_without_the_gripper_fingers(tmp_path, monkeypatch):
    """Real EAIK refuses more than 6 moving joints; a gripper's fingers aren't part of the arm's IK."""
    import xml.etree.ElementTree as ET
    from tests.ros_helpers import six_axis_with_gripper_zip
    seen = {}

    class UrdfRobot:
        def __init__(self, path):
            text = Path(path).read_text()
            moving = [j for j in ET.fromstring(text).iter("joint") if j.get("type") != "fixed"]
            if len(moving) > 6:
                raise RuntimeError("Currently, only 1-6R robots are solvable with EAIK.")
            seen["joints"] = [j.get("name") for j in moving]
            self.chain = parse_chain(text)

        def hasKnownDecomposition(self):
            return True

        def fwdKin(self, q):
            return fk(self.chain, q)

    sub = types.ModuleType("eaik.IK_URDF"); sub.UrdfRobot = UrdfRobot
    pkg = types.ModuleType("eaik"); pkg.IK_URDF = sub
    monkeypatch.setitem(sys.modules, "eaik", pkg)
    monkeypatch.setitem(sys.modules, "eaik.IK_URDF", sub)
    d = unzip(six_axis_with_gripper_zip(tmp_path), tmp_path / "x")
    src = tmp_path / "ws" / "src"
    generate("sixg", d / "sixg", src, source="sixg.zip", samples=50)
    monkeypatch.syspath_prepend(str(src / "sixg_kinematics"))
    for name in [m for m in sys.modules if m.startswith("sixg_kinematics")]:
        monkeypatch.delitem(sys.modules, name)
    k = importlib.import_module("sixg_kinematics").Kinematics(str(src / "sixg" / "urdf" / "sixg.urdf"))
    assert k._bot is not None, k._why
    assert seen["joints"] == [f"l{i}_joint" for i in range(1, 7)]
