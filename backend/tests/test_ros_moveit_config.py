def test_every_moveit_config_file_has_the_note(ws):
    files = [p for p in (ws / "bot_moveit_config").rglob("*") if p.is_file()]
    assert len(files) >= 12
    for p in files:
        assert NOTE in p.read_text(), p.name


def test_description_package_is_ament_even_from_an_old_zip(tmp_path):
    d = unzip(two_joint_zip(tmp_path), tmp_path / "x")
    (d / "bot" / "package.xml").write_text("<package format='2'><buildtool_depend>catkin</buildtool_depend></package>")
    (d / "bot" / "CMakeLists.txt").unlink()
    src = tmp_path / "ws" / "src"
    generate("bot", d / "bot", src, source="bot.zip", samples=50)
    assert ET.parse(src / "bot" / "package.xml").getroot().find("buildtool_depend").text == "ament_cmake"
    assert (src / "bot" / "CMakeLists.txt").exists()
    assert (src / "bot" / "meshes" / "hand.stl").exists()


def test_regenerating_replaces_generated_packages_and_keeps_user_tasks(ws, tmp_path):
    (ws / "bot_tasks").mkdir()
    (ws / "bot_tasks" / "mine.py").write_text("print('mine')")
    (ws / "bot_moveit_config" / "stale.txt").write_text("old")
    generate("bot", tmp_path / "x" / "bot", ws, source="bot.zip", samples=50)
    assert (ws / "bot_tasks" / "mine.py").read_text() == "print('mine')"
    assert not (ws / "bot_moveit_config" / "stale.txt").exists()


def test_invalid_ros_name_is_refused_without_output(tmp_path):
    d = unzip(two_joint_zip(tmp_path), tmp_path / "x")
    out = tmp_path / "ws" / "src"
    with pytest.raises(ValueError, match="Robot name 'My-Bot' is not a valid ROS package name"):
        generate("My-Bot", d / "bot", out, source="bot.zip", samples=50)
    assert not out.exists()


def test_unsupported_robot_leaves_no_output(tmp_path):
    d = unzip(two_joint_zip(tmp_path), tmp_path / "x")
    urdf = d / "bot" / "urdf" / "bot.urdf"
    urdf.write_text(urdf.read_text().replace('<limit lower="-1.5"', '<nolimit lower="-1.5"'))
    out = tmp_path / "ws" / "src"
    with pytest.raises(UnsupportedRobot, match="has no limits"):
        generate("bot", d / "bot", out, source="bot.zip", samples=50)
    assert not out.exists()


def test_irb1300_generates(irb1300_zip, tmp_path):
    with zipfile.ZipFile(irb1300_zip) as z:
        z.extractall(tmp_path / "x")
    src = tmp_path / "ws" / "src"
    generate("irb1300", tmp_path / "x" / "irb1300", src, source="irb1300.zip", samples=200)
    srdf = ET.parse(src / "irb1300_moveit_config" / "config" / "irb1300.srdf").getroot()
    assert srdf.find("group/chain").attrib == {"base_link": "base", "tip_link": "link6"}
    assert len(srdf.findall("group_state/joint")) == 6
