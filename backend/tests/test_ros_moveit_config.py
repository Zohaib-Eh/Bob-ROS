def _yaml(p):
    return yaml.safe_load(p.read_text())


def test_srdf_has_group_home_and_collision_skips(ws):
    srdf = ET.parse(ws / "bot_moveit_config" / "config" / "bot.srdf").getroot()
    chain = srdf.find("group/chain").attrib
    assert chain == {"base_link": "base", "tip_link": "hand"}
    assert {j.get("name"): j.get("value") for j in srdf.find("group_state").findall("joint")} == \
        {"arm_joint": "0.0", "hand_joint": "0.0"}
    skips = {(d.get("link1"), d.get("link2")): d.get("reason") for d in srdf.findall("disable_collisions")}
    assert skips == {("arm", "base"): "Adjacent", ("arm", "hand"): "Adjacent", ("base", "hand"): "Never"}


def test_yaml_configs_name_the_urdf_joints(ws):
    cfg = ws / "bot_moveit_config" / "config"
    names = ["arm_joint", "hand_joint"]
    assert _yaml(cfg / "ros2_controllers.yaml")["arm_controller"]["ros__parameters"]["joints"] == names
    assert _yaml(cfg / "moveit_controllers.yaml")["moveit_simple_controller_manager"]["arm_controller"]["joints"] == names
    assert list(_yaml(cfg / "joint_limits.yaml")["joint_limits"]) == names
    assert _yaml(cfg / "initial_positions.yaml")["initial_positions"] == {"arm_joint": 0.0, "hand_joint": 0.0}
    k = _yaml(cfg / "kinematics.yaml")["arm"]
    assert k == {"kinematics_solver": "trac_ik_kinematics_plugin/TRAC_IKKinematicsPlugin",
                 "kinematics_solver_timeout": 0.05, "solve_type": "Distance"}
    assert _yaml(cfg / "ompl_planning.yaml")["planning_plugins"] == ["ompl_interface/OMPLPlanner"]


def test_xacro_files_parse_and_list_every_joint(ws):
    cfg = ws / "bot_moveit_config" / "config"
