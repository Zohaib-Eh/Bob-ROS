"""Write a ROS 2 Jazzy workspace for a serial arm from its URDF: the description package, the
MoveIt config and (via kinematics_pkg) the exact-IK package. Plain text: no ROS needed here."""
import re
import shutil
import tempfile
from pathlib import Path

from app.export.urdf_writer import cmakelists, package_xml

from .chain import Chain, home, parse_chain
from .collisions import disabled_pairs, link_meshes

ROS_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
MAX_VELOCITY = 1.0       # rad/s (m/s for prismatic): placeholder until set from the datasheet
MAX_ACCELERATION = 2.0   # rad/s^2 (m/s^2)


def hash_note(source: str, robot: str) -> str:
    return (f"# Generated by cad-to-urdf from {source}. Regenerating overwrites this file.\n"
            f"# Put your own code in {robot}_tasks/.\n")


def xml_note(source: str, robot: str) -> str:
    source = source.replace("--", "-")  # "--" is not allowed inside an XML comment
    return (f"<!-- Generated by cad-to-urdf from {source}. Regenerating overwrites this file.\n"
            f"     Put your own code in {robot}_tasks/. -->\n")


def write_files(root: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")


def _srdf(chain: Chain, robot: str, pairs, note: str) -> str:
    state = "\n".join(f'    <joint name="{j.name}" value="{v!r}"/>' for j, v in zip(chain.joints, home(chain)))
    skips = "\n".join(f'  <disable_collisions link1="{a}" link2="{b}" reason="{r}"/>'
                      for (a, b), r in sorted(pairs.items()))
    return f"""<?xml version="1.0"?>
{note}<robot name="{robot}">
  <group name="arm">
    <chain base_link="{chain.base}" tip_link="{chain.tip}"/>
  </group>
  <group_state name="home" group="arm">
{state}
  </group_state>
  <!-- Link pairs MoveIt skips: joined by a joint (Adjacent), touching at home (Default),
       or never touching in random poses (Never). -->
{skips}
</robot>
"""


def _kinematics_yaml(robot: str, note: str) -> str:
    return note + f"""# Solver: TRAC-IK, a numeric solver that works on any serial chain.
# For every exact IK solution of a pose, use the {robot}_kinematics package.
arm:
  kinematics_solver: trac_ik_kinematics_plugin/TRAC_IKKinematicsPlugin
  kinematics_solver_timeout: 0.05
  solve_type: Distance
  # Alternative (apt install ros-jazzy-pick-ik):
  # kinematics_solver: pick_ik/PickIkPlugin
  # mode: global
"""


def _joint_limits_yaml(chain: Chain, note: str) -> str:
    lines = [note.rstrip("\n"),
             "# Position limits come from the URDF.",
             "# Velocity and acceleration are conservative placeholders: set them from the robot datasheet.",
             "default_velocity_scaling_factor: 0.1",
             "default_acceleration_scaling_factor: 0.1",
             "joint_limits:"]
    for j in chain.joints:
        unit = "m" if j.type == "prismatic" else "rad"
        lines += [f"  {j.name}:",
                  "    has_velocity_limits: true",
                  f"    max_velocity: {MAX_VELOCITY}  # {unit}/s, set from datasheet",
                  "    has_acceleration_limits: true",
                  f"    max_acceleration: {MAX_ACCELERATION}  # {unit}/s^2, set from datasheet"]
    return "\n".join(lines) + "\n"


def _controllers_yaml(names: str, note: str) -> str:
    return note + f"""controller_manager:
  ros__parameters:
    update_rate: 100
    arm_controller:
      type: joint_trajectory_controller/JointTrajectoryController
    joint_state_broadcaster:
      type: joint_state_broadcaster/JointStateBroadcaster

arm_controller:
  ros__parameters:
    joints: [{names}]
    command_interfaces: [position]
    state_interfaces: [position, velocity]
    allow_nonzero_velocity_at_trajectory_end: true
"""


def _moveit_controllers_yaml(names: str, note: str) -> str:
    return note + f"""moveit_controller_manager: moveit_simple_controller_manager/MoveItSimpleControllerManager
moveit_simple_controller_manager:
  controller_names: [arm_controller]
  arm_controller:
    type: FollowJointTrajectory
    action_ns: follow_joint_trajectory
    default: true
    joints: [{names}]
"""


def _ompl_yaml(note: str) -> str:
    return note + """planning_plugins:
  - ompl_interface/OMPLPlanner
request_adapters:
  - default_planning_request_adapters/ResolveConstraintFrames
  - default_planning_request_adapters/ValidateWorkspaceBounds
  - default_planning_request_adapters/CheckStartStateBounds
  - default_planning_request_adapters/CheckStartStateCollision
response_adapters:
  - default_planning_response_adapters/AddTimeOptimalParameterization
  - default_planning_response_adapters/ValidateSolution
  - default_planning_response_adapters/DisplayMotionPath
planner_configs:
  RRTConnectkConfigDefault:
    type: geometric::RRTConnect
    range: 0.0
arm:
  default_planner_config: RRTConnectkConfigDefault
  planner_configs: [RRTConnectkConfigDefault]
"""


def _ros2_control_xacro(chain: Chain, robot: str, note: str) -> str:
    joints = "\n".join(f"""      <joint name="{j.name}">
        <command_interface name="position"/>
        <state_interface name="position">
          <param name="initial_value">${{initial_positions['{j.name}']}}</param>
        </state_interface>
        <state_interface name="velocity"/>
      </joint>""" for j in chain.joints)
    return f"""<?xml version="1.0"?>
{note}<robot xmlns:xacro="http://www.ros.org/wiki/xacro">
  <xacro:macro name="{robot}_ros2_control" params="name initial_positions_file hardware">
    <xacro:property name="initial_positions" value="${{xacro.load_yaml(initial_positions_file)['initial_positions']}}"/>
    <ros2_control name="${{name}}" type="system">
      <hardware>
        <!-- hardware:=mock for now; Gazebo and MuJoCo arrive with the simulation container. -->
        <xacro:if value="${{hardware == 'mock'}}">
          <plugin>mock_components/GenericSystem</plugin>
        </xacro:if>
      </hardware>
{joints}
    </ros2_control>
  </xacro:macro>
</robot>
"""


def _urdf_xacro(robot: str, note: str) -> str:
    return f"""<?xml version="1.0"?>
{note}<robot xmlns:xacro="http://www.ros.org/wiki/xacro" name="{robot}">
  <xacro:arg name="initial_positions_file" default="$(find {robot}_moveit_config)/config/initial_positions.yaml"/>
  <xacro:arg name="hardware" default="mock"/>
  <xacro:include filename="$(find {robot})/urdf/{robot}.urdf"/>
  <xacro:include filename="{robot}.ros2_control.xacro"/>
  <xacro:{robot}_ros2_control name="{robot}" initial_positions_file="$(arg initial_positions_file)" hardware="$(arg hardware)"/>
</robot>
"""


def _launch(robot: str, note: str) -> str:
    return note + f'''"""MoveIt on mock hardware, headless: robot_state_publisher, ros2_control, controllers, move_group."""
from launch import LaunchDescription
from launch_ros.actions import Node
from moveit_configs_utils import MoveItConfigsBuilder


def generate_launch_description():
    cfg = MoveItConfigsBuilder("{robot}", package_name="{robot}_moveit_config").to_moveit_configs()
    controllers = str(cfg.package_path / "config" / "ros2_controllers.yaml")
    return LaunchDescription([
        Node(package="robot_state_publisher", executable="robot_state_publisher",
             parameters=[cfg.robot_description]),
        Node(package="controller_manager", executable="ros2_control_node",
             parameters=[controllers],
             remappings=[("~/robot_description", "/robot_description")]),
        Node(package="controller_manager", executable="spawner",
             arguments=["joint_state_broadcaster", "arm_controller"]),
        Node(package="moveit_ros_move_group", executable="move_group",
             parameters=[cfg.to_dict()]),
    ])
'''


def _package_xml(robot: str, note: str) -> str:
    deps = [robot, "moveit_ros_move_group", "moveit_configs_utils", "moveit_kinematics",
            "moveit_planners_ompl", "moveit_simple_controller_manager", "trac_ik_kinematics_plugin",
            "controller_manager", "joint_state_broadcaster", "joint_trajectory_controller",
            "robot_state_publisher", "xacro"]
    dep_lines = "\n".join(f"  <exec_depend>{d}</exec_depend>" for d in deps)
    return f"""<?xml version="1.0"?>
{note}<package format="3">
  <name>{robot}_moveit_config</name>
  <version>0.1.0</version>
  <description>MoveIt config for {robot}</description>
  <maintainer email="none@example.com">cad-to-urdf</maintainer>
  <license>BSD</license>
  <buildtool_depend>ament_cmake</buildtool_depend>
{dep_lines}
  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""


def moveit_files(chain: Chain, robot: str, source: str, pairs) -> dict[str, str]:
    h, x = hash_note(source, robot), xml_note(source, robot)
    names = ", ".join(j.name for j in chain.joints)
    initial = "\n".join(f"  {j.name}: {v!r}" for j, v in zip(chain.joints, home(chain)))
    return {
        f"config/{robot}.srdf": _srdf(chain, robot, pairs, x),
        "config/kinematics.yaml": _kinematics_yaml(robot, h),
        "config/joint_limits.yaml": _joint_limits_yaml(chain, h),
        "config/ros2_controllers.yaml": _controllers_yaml(names, h),
        "config/moveit_controllers.yaml": _moveit_controllers_yaml(names, h),
        "config/ompl_planning.yaml": _ompl_yaml(h),
        "config/initial_positions.yaml": h + f"initial_positions:\n{initial}\n",
        f"config/{robot}.ros2_control.xacro": _ros2_control_xacro(chain, robot, x),
        f"config/{robot}.urdf.xacro": _urdf_xacro(robot, x),
        "launch/demo.launch.py": _launch(robot, h),
        "CMakeLists.txt": h + f"""cmake_minimum_required(VERSION 3.8)
project({robot}_moveit_config)
find_package(ament_cmake REQUIRED)
install(DIRECTORY config launch DESTINATION share/${{PROJECT_NAME}})
ament_package()
""",
        "package.xml": _package_xml(robot, x),
    }


def generate(robot: str, description_dir: Path, out_src: Path, source: str, samples: int = 10000) -> None:
    """Write <robot>, <robot>_moveit_config (and <robot>_kinematics) into out_src.
    Everything is built in a temp folder first: an error leaves out_src untouched."""
    if not ROS_NAME.match(robot):
        raise ValueError(f"Robot name '{robot}' is not a valid ROS package name; use lowercase "
                         "letters, digits and underscores, starting with a letter.")
    description_dir = Path(description_dir)
    urdf_path = description_dir / "urdf" / f"{robot}.urdf"
    if not urdf_path.exists():
        raise ValueError("Not a cad-to-urdf export.")
    urdf = urdf_path.read_text(encoding="utf-8")
    chain = parse_chain(urdf)
    pairs = disabled_pairs(chain, link_meshes(urdf, description_dir), samples=samples)

    tmp = Path(tempfile.mkdtemp(prefix="cad-to-urdf-"))
    try:
        shutil.copytree(description_dir, tmp / robot)
        write_files(tmp / robot, {"package.xml": package_xml(robot), "CMakeLists.txt": cmakelists(robot)})
        write_files(tmp / f"{robot}_moveit_config", moveit_files(chain, robot, source, pairs))
        out_src = Path(out_src)
        out_src.mkdir(parents=True, exist_ok=True)
        for pkg in sorted(p.name for p in tmp.iterdir()):
            shutil.rmtree(out_src / pkg, ignore_errors=True)
            shutil.move(str(tmp / pkg), str(out_src / pkg))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
